#!/usr/bin/env python3
"""
build_card.py — rebuild a social quote card on a REAL camera frame.

The card "Investors Bet on Resilient Founders.png" was generated by OpenAI's image model
(C2PA: softwareAgent ChatGPT / gpt-image, digitalSourceType trainedAlgorithmicMedia).
It is a synthetic likeness of a real person and must not be published.

This script takes the same design — the same geometry, the same blue, the same icon row —
and rebuilds it over a real camera frame from the raw dump, so the post can ship.

    python3 engine/build_card.py \
        --photo engine/assets/IMG_2547.jpg \
        --template "engine/assets/Investors Bet on Resilient Founders.png" \
        --out "engine/assets/Investors Bet on Resilient Founders (real).png"
"""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, ImageFilter

BLUE = (1, 179, 242)
WHITE = (255, 255, 255)
BLACK = (0, 0, 0)
FONT_BOLD = "/System/Library/Fonts/Supplemental/Arial Bold.ttf"
FONT_BLACK = "/System/Library/Fonts/Supplemental/Arial Black.ttf"

# the four lines of the card, in order; "" means a white line with no bar
LINES = [
    "Investors don't bet on",
    "50-page pitch decks.",
    "They bet on founders who",
    "execute through uncertainty.",
]


def find_bars(im):
    """Locate the blue highlight rectangles in the template."""
    w, h = im.size
    px = im.load()
    rows = []
    for y in range(int(h * 0.5), h - 150):
        xs = [x for x in range(0, w, 2)
              if px[x, y][2] > 150 and px[x, y][2] - px[x, y][0] > 60]
        rows.append((y, (min(xs), max(xs)) if xs else None))
    bars, cur = [], None
    for y, span in rows:
        if span and span[1] - span[0] > 100:
            if cur and y - cur["y1"] <= 3:
                cur["y1"] = y
                cur["x0"] = min(cur["x0"], span[0]); cur["x1"] = max(cur["x1"], span[1])
            else:
                if cur:
                    bars.append(cur)
                cur = {"y0": y, "y1": y, "x0": span[0], "x1": span[1]}
        else:
            if cur:
                bars.append(cur); cur = None
    if cur:
        bars.append(cur)
    return [b for b in bars if b["y1"] - b["y0"] > 20]


def fit_font(text, target_w, path=FONT_BOLD, pad=24):
    """Pick the font size so `text` fills target_w - 2*pad."""
    size = 20
    while size < 200:
        f = ImageFont.truetype(path, size)
        w = f.getbbox(text)[2] - f.getbbox(text)[0]
        if w > target_w - 2 * pad:
            return ImageFont.truetype(path, max(8, size - 2))
        size += 2
    return ImageFont.truetype(path, size)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--photo", required=True)
    ap.add_argument("--template", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--icon-src", default=None, help="png to lift the clean icon row from")
    ap.add_argument("--anchor", default="0.0", help="vertical crop anchor: 0 = top of frame, 0.5 = centre")
    ap.add_argument("--crop", default=None, help="source-pixel crop, x0,y0,x1,y1 (before scaling)")
    args = ap.parse_args()

    tpl = Image.open(args.template).convert("RGB")
    W, H = tpl.size
    photo = Image.open(args.photo).convert("RGB")
    if args.crop:
        x0, y0, x1, y1 = [int(v) for v in args.crop.split(",")]
        photo = photo.crop((x0, y0, x1, y1))
    bars = find_bars(tpl)
    if len(bars) < 3:
        raise SystemExit(f"expected 3 blue bars, found {len(bars)}")

    canvas = Image.new("RGB", (W, H), BLACK)

    # 1. the photo fills the top, above the first bar
    photo_top = 0
    photo_bottom = bars[0]["y0"] - 10
    ph = photo_bottom - photo_top
    pw, phh = photo.size
    scale = max(W / pw, ph / phh)
    rs = photo.resize((int(pw * scale), int(phh * scale)), Image.LANCZOS)
    left = (rs.width - W) // 2
    top = int((rs.height - ph) * float(args.anchor))   # 0 = top of frame, 0.5 = centre
    canvas.paste(rs.crop((left, top, left + W, top + ph)), (0, photo_top))

    # 2. feather the photo into the black panel
    fade = Image.new("L", (1, 220), 0)
    d = ImageDraw.Draw(fade)
    for i in range(220):
        d.point((0, i), fill=int(255 * (i / 220) ** 1.6))
    mask = Image.new("L", (W, H), 0)
    mask.paste(fade, (0, photo_bottom - 220))
    canvas.paste(Image.new("RGB", (W, H), BLACK), (0, 0), mask)

    # 3. the bars, exactly where the template had them
    draw = ImageDraw.Draw(canvas)
    for b in bars:
        draw.rectangle([b["x0"], b["y0"], b["x1"], b["y1"]], fill=BLUE)

    # 4. the four lines
    bar_w = bars[0]["x1"] - bars[0]["x0"]
    # line 1 -> bar 1, line 2 -> bar 2, line 3 -> white (no bar), line 4 -> bar 3
    placements = [
        (LINES[0], bars[0], True),
        (LINES[1], bars[1], True),
        (LINES[2], None, False),
        (LINES[3], bars[2], True),
    ]
    for text, bar, on_bar in placements:
        if on_bar:
            w = bar["x1"] - bar["x0"]
            f = fit_font(text, w, FONT_BOLD)
            bbox = f.getbbox(text)
            tw = bbox[2] - bbox[0]
            x = bar["x0"] + 24
            y = bar["y0"] + (bar["y1"] - bar["y0"] - (bbox[3] - bbox[1])) / 2 - bbox[1]
            draw.text((x, y), text, font=f, fill=WHITE)
        else:
            # sit in the gap between bar 2 and bar 3
            ytop = bars[1]["y1"]
            ybot = bars[2]["y0"]
            w = bar_w
            f = fit_font(text, w, FONT_BOLD)
            bbox = f.getbbox(text)
            x = bars[0]["x0"] + 6
            y = ytop + (ybot - ytop - (bbox[3] - bbox[1])) / 2 - bbox[1]
            draw.text((x, y), text, font=f, fill=WHITE)

    # 5. the footer (icon row + website), lifted whole from the template so the glyphs
    #    and their baseline stay exactly as designed. Measured footer band: icons
    #    1239-1298, URL 1258-1284 on a 1394px card; the band keeps a small margin.
    src = args.icon_src or args.template
    src_im = Image.open(src).convert("RGB")
    W2, H2 = src_im.size
    if (W2, H2) != (W, H):
        raise SystemExit(f"icon source is {W2}x{H2}, template is {W}x{H}")
    band_top = int(H * 0.878)          # 1223 on a 1394px card
    band_bottom = int(H * 0.947)       # 1320
    band = src_im.crop((0, band_top, W, band_bottom))
    # the template's "black" is (3,3,3); paste only the glyph pixels so no seam shows
    band_mask = band.convert("L").point(lambda v: 255 if v > 6 else 0)
    canvas.paste(band, (0, band_top), band_mask)

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    canvas.save(out)
    print(f"wrote {out}  ({out.stat().st_size/1e6:.1f} MB)")


if __name__ == "__main__":
    main()
